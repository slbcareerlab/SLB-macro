// 출시판 중지용 파일: 매크로 기능이 전혀 들어 있지 않으며, 페이지를 열면 안내만 한 번 띄웁니다.
// 불러오기 스크립트가 이 파일을 정상 파일로 받아 기기에 저장된 예전 버전을 덮어쓰도록 크기와 표식을 맞췄습니다.
(function __SLB_MAIN__() {
  'use strict';
  if (window.__SLB_OFF_SHOWN__) return;
  window.__SLB_OFF_SHOWN__ = true;
  try {
    const d = document.createElement('div');
    d.textContent = 'SLB 매크로 출시판은 지금 쉬는 중입니다. 매크로가 실행되지 않습니다.';
    d.style.cssText = 'position:fixed;left:8px;right:8px;top:calc(8px + env(safe-area-inset-top));z-index:2147483647;background:#334155;color:#fff;font:600 13px/1.4 -apple-system,system-ui,sans-serif;padding:8px 10px;border-radius:10px;text-align:center;pointer-events:none';
    (document.body || document.documentElement).appendChild(d);
    setTimeout(() => d.remove(), 5000);
  } catch (e) {}
})();
